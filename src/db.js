function normalizeParams(params) {
  if (params.length === 1 && Array.isArray(params[0])) return params[0];
  return params;
}

function postgresSql(sql) {
  let index = 0;
  return sql.replace(/\?/g, () => `$${++index}`);
}

class SqliteDatabase {
  constructor(filename) {
    if (filename !== ':memory:') {
      fs.mkdirSync(path.dirname(filename), { recursive: true });
    }
    this.db = new DatabaseSync(filename);
  }

  async get(sql, ...params) {
    return this.db.prepare(sql).get(...normalizeParams(params)) || null;
  }

  async all(sql, ...params) {
    return this.db.prepare(sql).all(...normalizeParams(params));
  }

  async run(sql, ...params) {
    return this.db.prepare(sql).run(...normalizeParams(params));
  }

  async exec(sql) {
    this.db.exec(sql);
  }

  async transaction(callback) {
    this.db.exec('BEGIN IMMEDIATE');
    try {
      const result = await callback(this);
      this.db.exec('COMMIT');
      return result;
    } catch (error) {
      this.db.exec('ROLLBACK');
      throw error;
    }
  }
}

class PostgresDatabase {
  constructor(queryable, pool = queryable) {
    this.queryable = queryable;
    this.pool = pool;
  }

  async get(sql, ...params) {
    const result = await this.queryable.query(postgresSql(sql), normalizeParams(params));
    return result.rows[0] || null;
  }

  async all(sql, ...params) {
    const result = await this.queryable.query(postgresSql(sql), normalizeParams(params));
    return result.rows;
  }

  async run(sql, ...params) {
    const result = await this.queryable.query(postgresSql(sql), normalizeParams(params));
    return {
      changes: result.rowCount,
      lastInsertRowid: result.rows[0]?.id,
    };
  }

  async exec(sql) {
    await this.queryable.query(sql);
  }

  async transaction(callback) {
    const client = await this.pool.connect();
    const tx = new PostgresDatabase(client, this.pool);
    try {
      await client.query('BEGIN');
      const result = await callback(tx);
      await client.query('COMMIT');
      return result;
    } catch (error) {
      await client.query('ROLLBACK');
      throw error;
    } finally {
      client.release();
    }
  }
}

async function migrate(db, schema) {
  await db.exec(schema);
  const gameplayVersion = await db.get("SELECT value FROM app_meta WHERE key = 'gameplay_version'");
  if (gameplayVersion?.value !== '3') {
    await db.exec(`
      DELETE FROM achievements;
      DELETE FROM wagers;
      DELETE FROM daily_runs;
      INSERT INTO app_meta (key, value) VALUES ('gameplay_version', '3')
      ON CONFLICT(key) DO UPDATE SET value = excluded.value;
    `);
  }
}

async function createSqliteDatabase(filename) {
  const db = new SqliteDatabase(filename);
  await db.exec('PRAGMA foreign_keys = ON; PRAGMA journal_mode = WAL;');
  await migrate(db, sqliteSchema);
  return db;
}

async function createPostgresDatabase(connectionString) {
  const { Pool } = await import('pg');
  const pool = new Pool({ connectionString });
  const db = new PostgresDatabase(pool);
  await migrate(db, postgresSchema);
  return db;
}

export async function createDatabase(options) {
  if (typeof options === 'string') return createSqliteDatabase(options);
  if (options.databaseUrl) return createPostgresDatabase(options.databaseUrl);
  return createSqliteDatabase(options.databasePath);
}
