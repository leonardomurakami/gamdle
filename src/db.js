import fs from 'node:fs';
import path from 'node:path';
import { DatabaseSync } from 'node:sqlite';

const sqliteSchema = `
  CREATE TABLE IF NOT EXISTS users (
    id INTEGER PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    username TEXT,
    created_at INTEGER NOT NULL
  );

  CREATE TABLE IF NOT EXISTS auth_tokens (
    id INTEGER PRIMARY KEY,
    token_hash TEXT NOT NULL UNIQUE,
    email TEXT NOT NULL,
    purpose TEXT NOT NULL,
    user_id INTEGER,
    metadata TEXT,
    expires_at INTEGER NOT NULL,
    used_at INTEGER,
    created_at INTEGER NOT NULL,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
  );

  CREATE TABLE IF NOT EXISTS sessions (
    id INTEGER PRIMARY KEY,
    token_hash TEXT NOT NULL UNIQUE,
    user_id INTEGER NOT NULL,
    expires_at INTEGER NOT NULL,
    created_at INTEGER NOT NULL,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
  );

  CREATE TABLE IF NOT EXISTS auth_attempts (
    id INTEGER PRIMARY KEY,
    email TEXT NOT NULL,
    ip TEXT NOT NULL,
    created_at INTEGER NOT NULL
  );

  CREATE TABLE IF NOT EXISTS daily_runs (
    id INTEGER PRIMARY KEY,
    user_id INTEGER NOT NULL,
    run_date TEXT NOT NULL,
    bankroll INTEGER NOT NULL DEFAULT 1000,
    move_number INTEGER NOT NULL DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'active',
    user_seed TEXT NOT NULL DEFAULT '',
    game_order TEXT NOT NULL DEFAULT '[]',
    finished_at INTEGER,
    created_at INTEGER NOT NULL,
    UNIQUE (user_id, run_date),
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
  );

  CREATE TABLE IF NOT EXISTS wagers (
    id INTEGER PRIMARY KEY,
    run_id INTEGER NOT NULL,
    move_number INTEGER NOT NULL,
    table_key TEXT NOT NULL,
    bet_json TEXT NOT NULL,
    stake INTEGER NOT NULL,
    event_json TEXT NOT NULL,
    won INTEGER NOT NULL,
    probability REAL NOT NULL,
    multiplier REAL NOT NULL,
    bankroll_after INTEGER NOT NULL,
    net_change INTEGER NOT NULL,
    created_at INTEGER NOT NULL,
    UNIQUE (run_id, move_number),
    FOREIGN KEY (run_id) REFERENCES daily_runs(id) ON DELETE CASCADE
  );

  CREATE TABLE IF NOT EXISTS achievements (
    id INTEGER PRIMARY KEY,
    user_id INTEGER NOT NULL,
    achievement_key TEXT NOT NULL,
    first_date TEXT NOT NULL,
    unlocked_at INTEGER NOT NULL,
    UNIQUE (user_id, achievement_key),
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
  );

  CREATE INDEX IF NOT EXISTS auth_attempts_recent ON auth_attempts (created_at);
  CREATE INDEX IF NOT EXISTS runs_leaderboard ON daily_runs (run_date, status, bankroll DESC);

  CREATE TABLE IF NOT EXISTS app_meta (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
  );
`;

